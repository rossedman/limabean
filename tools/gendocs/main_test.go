package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestGenerate(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "commands")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	stale := filepath.Join(dir, "limabean_gone.md")
	if err := os.WriteFile(stale, []byte("old"), 0o644); err != nil {
		t.Fatal(err)
	}
	var stderr bytes.Buffer
	if code := run([]string{dir}, &stderr); code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Error("a page for a removed command should be deleted")
	}
	for _, page := range []string{"limabean.md", "limabean_up.md", "limabean_snapshot_save.md"} {
		b, err := os.ReadFile(filepath.Join(dir, page))
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(string(b), "Auto generated by") {
			t.Errorf("%s has a date stamp, so it changes on every build", page)
		}
	}
}

func TestGenerateFails(t *testing.T) {
	file := filepath.Join(t.TempDir(), "file")
	if err := os.WriteFile(file, nil, 0o644); err != nil {
		t.Fatal(err)
	}
	var stderr bytes.Buffer
	if code := run([]string{file}, &stderr); code != 1 || !strings.Contains(stderr.String(), "gendocs:") {
		t.Errorf("a file in the way: exit %d, %q", code, stderr.String())
	}
}
