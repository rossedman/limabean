package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func write(t *testing.T, dir, name, body string) {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

const clean = "// Package a does things.\npackage a\n\n// F does a thing.\nfunc F() {}\n"

func TestCheck(t *testing.T) {
	tests := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{"clean", map[string]string{"a.go": clean}, nil},
		{"missing func doc", map[string]string{"a.go": "// Package a does things.\npackage a\n\nfunc F() {}\n"},
			[]string{"a.go:4: F has no doc comment"}},
		{"missing method doc", map[string]string{"a.go": "// Package a does things.\npackage a\n\ntype T int\n\nfunc (T) M() {}\n"},
			[]string{"a.go:6: M has no doc comment"}},
		{"missing package comment", map[string]string{"a.go": "package a\n\n// F does a thing.\nfunc F() {}\n"},
			[]string{"package has no package comment"}},
		{"package comment in other file", map[string]string{
			"a.go":   "package a\n\n// F does a thing.\nfunc F() {}\n",
			"doc.go": "// Package a does things.\npackage a\n"}, nil},
		{"generated skipped", map[string]string{
			"a.go":   clean,
			"gen.go": "// Code generated by x. DO NOT EDIT.\n\npackage a\n\nfunc G() {}\n"}, nil},
		{"test files skipped", map[string]string{
			"a.go":      clean,
			"a_test.go": "package a\n\nfunc TestX() {}\n"}, nil},
		{"only test file ignored", map[string]string{"a_test.go": "package a\n\nfunc TestX() {}\n"}, nil},
		{"hidden and skipped dirs", map[string]string{
			"a.go":                clean,
			".hidden/x.go":        "package x\n\nfunc X() {}\n",
			"node_modules/y/y.go": "package y\n\nfunc Y() {}\n",
			"dist/z.go":           "package z\n\nfunc Z() {}\n"}, nil},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			for n, b := range tt.files {
				write(t, dir, n, b)
			}
			got, err := check(dir)
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != len(tt.want) {
				t.Fatalf("got %v, want %v", got, tt.want)
			}
			for i, w := range tt.want {
				if !strings.HasSuffix(got[i], w) {
					t.Errorf("got %q, want suffix %q", got[i], w)
				}
			}
		})
	}
}

func TestCheckErrors(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "bad.go", "package a\nfunc {")
	if _, err := check(dir); err == nil {
		t.Error("want parse error")
	}
	if _, err := check(filepath.Join(dir, "missing")); err == nil {
		t.Error("want walk error")
	}
}

func TestRun(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "a.go", clean)
	var out bytes.Buffer
	if code := run([]string{dir + "/..."}, &out); code != 0 || out.Len() != 0 {
		t.Fatalf("clean: code %d out %q", code, out.String())
	}

	write(t, dir, "b/b.go", "package b\n\nfunc B() {}\n")
	out.Reset()
	if code := run([]string{dir}, &out); code != 1 {
		t.Fatalf("findings: code %d", code)
	}
	if !strings.Contains(out.String(), "B has no doc comment") {
		t.Errorf("output %q", out.String())
	}

	out.Reset()
	if code := run([]string{filepath.Join(dir, "nope")}, &out); code != 2 {
		t.Fatalf("error: code %d", code)
	}
}

func TestRunDefaultArg(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "a.go", clean)
	t.Chdir(dir)
	var out bytes.Buffer
	if code := run(nil, &out); code != 0 {
		t.Fatalf("code %d out %q", code, out.String())
	}
	out.Reset()
	if code := run([]string{"..."}, &out); code != 0 {
		t.Fatalf("code %d out %q", code, out.String())
	}
}
